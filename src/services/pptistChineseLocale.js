const normalize = (value) => String(value || '').replace(/\s+/g, ' ').trim()

const textMap = new Map(Object.entries(UI_TEXT).map(([key, value]) => [normalize(key), value]))

const translateDynamic = (text) => {
  let match = text.match(/^Slide\s+(\d+)\s*\/\s*(\d+)$/i)
  if (match) return `幻灯片 ${match[1]} / ${match[2]}`

  match = text.match(/^Slide\s+(\d+)$/i)
  if (match) return `幻灯片 ${match[1]}`

  match = text.match(/^Slide page\s+(\d+)$/i)
  if (match) return `幻灯片页 ${match[1]}`

  match = text.match(/^Notes for slide\s+(\d+)$/i)
  if (match) return `幻灯片 ${match[1]} 备注`

  match = text.match(/^Selection\s+\((\d+)\/(\d+)\)$/i)
  if (match) return `选择窗格（${match[1]}/${match[2]}）`

  match = text.match(/^Table\s+(\d+)\s*×\s*(\d+)$/i)
  if (match) return `表格 ${match[1]} × ${match[2]}`

  match = text.match(/^Category\s+(\d+)$/i)
  if (match) return `分类 ${match[1]}`

  match = text.match(/^Series\s+(\d+)$/i)
  if (match) return `系列 ${match[1]}`

  match = text.match(/^Point\s+(\d+)$/i)
  if (match) return `点 ${match[1]}`

  match = text.match(/^Section\s+(\d+)$/i)
  if (match) return `章节 ${match[1]}`

  match = text.match(/^Theme color\s+(\d+):$/i)
  if (match) return `主题色 ${match[1]}：`

  match = text.match(/^Slide theme color\s+(\d+):$/i)
  if (match) return `幻灯片主题色 ${match[1]}：`

  match = text.match(/^Canvas size:\s*(\d+)\s*×\s*(\d+)$/i)
  if (match) return `画布尺寸：${match[1]} × ${match[2]}`

  return ''
}

const translateValue = (value) => {
  const normalized = normalize(value)
  if (!normalized) return ''
  return textMap.get(normalized) || translateDynamic(normalized)
}

const isDesignTab = (label) => ['设计', 'Design'].includes(label)
const isTransitionTab = (label) => ['切换', 'Transition'].includes(label)
const isAnimationTab = (label) => ['动画', 'Animation'].includes(label)

const resetHostTab = (tab) => {
  if (tab.dataset.pptistHostHidden === 'true') {
    tab.hidden = false
    tab.style.display = ''
    delete tab.dataset.pptistHostHidden
  }
  if (tab.dataset.pptistHostFlex === 'true') {
    tab.style.flex = ''
    delete tab.dataset.pptistHostFlex
  }
}

const hideHostTab = (tab) => {
  tab.dataset.pptistHostHidden = 'true'
  tab.hidden = true
  tab.style.display = 'none'
}

const simplifySlideToolbarTabs = (root) => {
  root.querySelectorAll('.toolbar .tabs.card').forEach((tabs) => {
    const tabList = [...tabs.querySelectorAll('.tab')]
    const labels = tabList.map((tab) => normalize(tab.textContent))
    const isSlideLevelTabs = labels.some(isDesignTab) && labels.some(isTransitionTab) && labels.some(isAnimationTab)

    tabs.classList.toggle('pptist-slide-tabs-only-design', isSlideLevelTabs)

    if (!isSlideLevelTabs) {
      tabList.forEach(resetHostTab)
      return
    }

    const designTab = tabList.find((tab) => isDesignTab(normalize(tab.textContent)))
    if (designTab && !designTab.classList.contains('active')) designTab.click()

    tabList.forEach((tab) => {
      if (isDesignTab(normalize(tab.textContent))) {
        resetHostTab(tab)
        tab.dataset.pptistHostFlex = 'true'
        tab.style.flex = '1 1 100%'
        return
      }
      hideHostTab(tab)
    })
  })
}

const isInsideEditableCanvas = (element) => {
  if (!element || element.nodeType !== Node.ELEMENT_NODE) return false
  return Boolean(element.closest(SKIP_SELECTOR))
}

const belongsToPptistUi = (element, root) => {
  if (!element || element.nodeType !== Node.ELEMENT_NODE) return false
  if (root.contains(element)) return true
  return Boolean(element.closest(FLOATING_UI_SELECTOR))
}

const translateTextNode = (node, root) => {
  const parent = node.parentElement
  if (!parent || !belongsToPptistUi(parent, root) || isInsideEditableCanvas(parent)) return

  const raw = node.nodeValue || ''
  const trimmed = raw.trim()
  const translated = translateValue(trimmed)
  if (!translated || translated === trimmed) return

  const leading = raw.match(/^\s*/)?.[0] || ''
  const trailing = raw.match(/\s*$/)?.[0] || ''
  node.nodeValue = `${leading}${translated}${trailing}`
}

const translateAttributes = (element, root) => {
  if (!belongsToPptistUi(element, root) || isInsideEditableCanvas(element)) return

  ATTRIBUTE_NAMES.forEach((attr) => {
    const value = element.getAttribute(attr)
    if (!value) return
    const translated = translateValue(value)
    if (translated && translated !== value) element.setAttribute(attr, translated)
  })
}

const walk = (node, root) => {
  if (!node) return
  if (node.nodeType === Node.TEXT_NODE) {
    translateTextNode(node, root)
    return
  }
  if (node.nodeType !== Node.ELEMENT_NODE) return

  const element = node
  translateAttributes(element, root)
  if (isInsideEditableCanvas(element)) return

  element.childNodes.forEach((child) => walk(child, root))
}

export const installPptistChineseLocalization = (root) => {
  if (!root || typeof MutationObserver === 'undefined') return () => {}

  root.setAttribute('data-pptist-locale', 'zh-CN')
  let pending = false

  const translate = () => {
    pending = false
    walk(root, root)
    simplifySlideToolbarTabs(root)
  }

  const scheduleTranslate = () => {
    if (pending) return
    pending = true
    window.requestAnimationFrame(translate)
  }

  translate()

  const observer = new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      if (mutation.type === 'characterData') {
        translateTextNode(mutation.target, root)
        continue
      }
      if (mutation.type === 'attributes') {
        translateAttributes(mutation.target, root)
        continue
      }
      mutation.addedNodes.forEach((node) => walk(node, root))
    }
    simplifySlideToolbarTabs(root)
    scheduleTranslate()
  })

  observer.observe(document.body, {
    childList: true,
    subtree: true,
    characterData: true,
    attributes: true,
    attributeFilter: ATTRIBUTE_NAMES
  })

  window.setTimeout(scheduleTranslate, 0)
  window.setTimeout(scheduleTranslate, 250)

  return () => observer.disconnect()
}
